function sample(items, count) {
	const copy = [...items];
	for (let i = copy.length - 1; i > 0; i--) {
		const j = Math.floor(Math.random() * (i + 1));
		const a = copy[i];
		copy[i] = copy[j];
		copy[j] = a;
	}
	return copy.slice(0, Math.min(count, copy.length));
}
