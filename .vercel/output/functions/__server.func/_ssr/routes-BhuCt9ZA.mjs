function generateFate(profile, years) {
	const who = heroWord(profile);
	const pool = FATE.filter((entry) => entry.years === years);
	const entry = pick(pool.length > 0 ? pool : FATE);
	const g = profile.gender;
	const span = yearsPhrase(years);
	const blocks = [{
		kind: "p",
		text: form(g, entry.body)
	}, {
		kind: "aside",
		label: "После",
		body: form(g, entry.coda)
	}];
	const title = displayName(profile) ? `${who} · ${span} спустя` : `${span.charAt(0).toUpperCase()}${span.slice(1)} спустя`;
	return {
		chapter: "Глава IV",
		kicker: "Хроника последствий",
		title,
		blocks,
		plainText: toPlainText(title, blocks)
	};
}
