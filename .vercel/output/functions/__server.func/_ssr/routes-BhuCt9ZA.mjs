function toPlainText(title, blocks) {
	const lines = [title, ""];
	for (const block of blocks) if (block.kind === "p") lines.push(block.text, "");
	else if (block.kind === "entry") lines.push(`${block.label} — ${block.body}`, "");
	else if (block.kind === "swatches") {
		for (const color of block.colors) lines.push(`${color.nameEn} / ${color.nameRu} — ${color.hex} (${color.role})`);
		lines.push("");
	} else if (block.kind === "namecard") {
		const c = block.card;
		lines.push(c.display);
		lines.push(`Значение — ${c.meaning}`);
		lines.push(`Происхождение — ${c.origin}`);
		lines.push(`Сокращения — ${c.nick}`);
		lines.push(`Контекст — ${c.context}`);
		lines.push("");
	} else lines.push(`${block.label}: ${block.body}`, "");
	return lines.join("\n").trim();
}
