export function generateFate(profile: HeroProfile, years: FateYears): Manuscript {
  const who = heroWord(profile);
  const pool = FATE.filter((entry) => entry.years === years);
  const entry = pick(pool.length > 0 ? pool : FATE);
  const g = profile.gender;
  const span = yearsPhrase(years);
  const blocks: Block[] = [
    { kind: "p", text: form(g, entry.body) },
    { kind: "aside", label: "После", body: form(g, entry.coda) },
  ];
  const title = displayName(profile)
    ? `${who} · ${span} спустя`
    : `${span.charAt(0).toUpperCase()}${span.slice(1)} спустя`;
  return {
    chapter: "Глава IV",
    kicker: "Хроника последствий",
    title,
    blocks,
    plainText: toPlainText(title, blocks),
  };
}

export function generateForTab(
  tab: TabId,
  profile: HeroProfile,
  years: FateYears = 5,
): Manuscript {
  if (tab === "relations") return generateRelations(profile);
  if (tab === "day") return generateDay(profile);
  if (tab === "secrets") return generateSecrets(profile);
  return generateFate(profile, years);
}
