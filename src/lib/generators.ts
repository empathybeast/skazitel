export function generateRelations(profile: HeroProfile): Manuscript {
  const people = sample(ROLES, Math.floor(Math.random() * 3) + 3);
  const traits = sample(TRAITS, people.length);
  const events = sample(RELATION_EVENTS, people.length);
  const blocks: Block[] = people.map((role, i) => {
    const trait = npcForm(role.gender, traits[i]!);
    const event = events[i]!(role.gender, profile.gender);
    return {
      kind: "entry",
      label: role.label.replace(/^./, (c) => c.toUpperCase()),
      body: `${trait}. ${event}`,
    };
  });
  blocks.push({ kind: "aside", label: "Узел", body: pick(CONFLICTS) });

  const title = displayName(profile)
    ? `${displayName(profile)} · окружение`
    : "Сеть вокруг героя";

  return {
    chapter: "Глава I",
    kicker: "Родословная и связи",
    title,
    blocks,
    plainText: toPlainText(title, blocks),
  };
}

