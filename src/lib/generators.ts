export type Block =
  | { kind: "p"; text: string }
  | { kind: "entry"; label: string; body: string }
  | { kind: "aside"; label: string; body: string }
  | { kind: "swatches"; colors: Swatch[] }
  | { kind: "namecard"; card: NameCard };

export type Manuscript = {
  chapter: string;
  kicker: string;
  title: string;
  blocks: Block[];
  plainText: string;
};

type Gendered = { m: string; f: string; u: string };

export function pick<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)]!;
}

export function sample<T>(items: readonly T[], count: number): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const a = copy[i]!;
    copy[i] = copy[j]!;
    copy[j] = a;
  }
  return copy.slice(0, Math.min(count, copy.length));
}

function form(gender: HeroGender, parts: Gendered): string {
  return parts[gender];
}

function npcForm(gender: NpcGender, parts: { m: string; f: string }): string {
  return parts[gender];
}

function displayName(profile: HeroProfile): string | null {
  const n = profile.name.trim();
  return n.length > 0 ? n : null;
}

function heroWord(profile: HeroProfile): string {
  const n = displayName(profile);
  if (n) return n;
  if (profile.gender === "f") return "героиня";
  return "герой";
}

export function toPlainText(title: string, blocks: Block[]): string {
  const lines: string[] = [title, ""];
  for (const block of blocks) {
    if (block.kind === "p") lines.push(block.text, "");
    else if (block.kind === "entry") lines.push(`${block.label} — ${block.body}`, "");
    else if (block.kind === "swatches") {
      for (const color of block.colors) {
        lines.push(`${color.nameEn} / ${color.nameRu} — ${color.hex} (${color.role})`);
      }
      lines.push("");
    } else if (block.kind === "namecard") {
      const c = block.card;
      lines.push(c.display);
      lines.push(`Значение — ${c.meaning}`);
      lines.push(`Происхождение — ${c.origin}`);
      lines.push(`Сокращения — ${c.nick}`);
      lines.push(`Контекст — ${c.context}`);
      lines.push("");
    } else lines.push(`${block.label}: ${block.body}`, "");
  }
  return lines.join("\n").trim();
}

function yearsPhrase(years: FateYears): string {
  if (years === 1) return "один год";
  if (years === 5) return "пять лет";
  return "двадцать лет";
}

